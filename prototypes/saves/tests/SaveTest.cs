using System;
using System.Linq;
using System.Threading;
using Godot;

namespace Saves.Tests;

/// <summary>
/// Headless tests of the save system and zones. Run with:
///   godot --headless --path prototypes/saves res://tests/SaveTest.tscn
/// Optional: -- --only=crash,kills,soak,... to run some groups (see CoreTests.Run and ZoneTests).
/// Exits 0 if every check passes, 1 if any fails, including if anything throws or hangs.
/// </summary>
public partial class SaveTest : Node
{
    /// <summary>Longer than a slow machine needs for everything; a hang must fail, never sit there.</summary>
    static readonly TimeSpan Watchdog = TimeSpan.FromMinutes(25);

    readonly TestLog _log = new();
    DateTime _started;
    System.Threading.Timer _watchdog;

    public override void _Ready()
    {
        _started = DateTime.UtcNow;
        _watchdog = new System.Threading.Timer(_ =>
        {
            GD.PrintErr($"FAIL  watchdog: the tests were still running after {Watchdog.TotalMinutes} minutes");
            System.Environment.Exit(1);
        }, null, Watchdog, Timeout.InfiniteTimeSpan);

        try
        {
            Run();
        }
        catch (Exception e)
        {
            // An exception in _Ready would otherwise be logged and the test would never quit.
            _log.Fail($"unexpected {e.GetType().Name}: {e.Message}\n{e.StackTrace}");
            Finish();
        }
    }

    void Run()
    {
        string only = null;
        foreach (string arg in OS.GetCmdlineUserArgs())
        {
            if (arg.StartsWith("--only=")) only = arg["--only=".Length..];
            if (arg == "--write-v1-fixture")
            {
                // One-off: the fixture is checked in and must never be regenerated by later builds.
                CoreTests.WriteV1Fixture(ProjectSettings.GlobalizePath("res://tests/fixtures/save-v1"));
                GD.Print("wrote tests/fixtures/save-v1");
                Finish();
                return;
            }
        }
        string[] groups = only?.Split(',');
        bool Wanted(string group) => groups == null || groups.Contains(group);

        var core = new CoreTests(_log, DataPaths.Fresh("test-run"))
        {
            WorkerDll = ProjectSettings.GlobalizePath("res://tests/SaveWorker/bin/Debug/net10.0/SaveWorker.dll"),
            FixtureV1 = ProjectSettings.GlobalizePath("res://tests/fixtures/save-v1"),
        };
        core.Run(Wanted);

        if (Wanted("zones"))
        {
            var zones = new ZoneTests(_log, DataPaths.Fresh("test-zones"));
            zones.Finished += Finish;
            AddChild(zones);
        }
        else Finish();
    }

    void Finish()
    {
        _watchdog?.Dispose();
        GD.Print($"\n{_log.Passes} passed, {_log.Failures} failed in {(DateTime.UtcNow - _started).TotalSeconds:F0} s");
        GD.Print(_log.Failures == 0 ? "ALL PASSED" : $"{_log.Failures} CHECK(S) FAILED");
        GetTree().Quit(_log.Failures == 0 ? 0 : 1);
    }
}
